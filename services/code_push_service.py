import re
import subprocess
import time
from pathlib import Path

from models.automation_artifact import AutomationArtifact
from domain.workspace.workspace_artifact import WorkspaceArtifact
from utils.logger import logger


class CodePushService:
    """
    Handles git branch creation, file commit, remote push, and optional
    PR creation for QAgentic-generated or self-healed test automation code.
    """

    def prepare(
        self,
        task,
        context,
        automation_artifact: AutomationArtifact,
        workspace_artifact: WorkspaceArtifact,
    ) -> dict:
        """
        Compute the push plan.  Called during the approval-request phase.
        The plan dict is stored inside the ApprovalRequest so the push
        phase can retrieve it without recomputing.
        """
        requirement = getattr(context, "requirement", "") or ""
        branch_name = self._generate_branch_name(requirement)
        commit_message = (
            f"feat(qagentic): add automated test code\n\n{task.description}"
        )

        return {
            "workspace_path": workspace_artifact.path,
            "branch_name": branch_name,
            "commit_message": commit_message,
            "files": [f.path for f in automation_artifact.files],
            "file_count": len(automation_artifact.files),
            "repository_url": workspace_artifact.repository_url,
        }

    def push(
        self,
        plan: dict,
        automation_artifact: AutomationArtifact,
    ) -> dict:
        """
        Execute git operations and return a result summary.

        Steps:
          1. Write automation files into the cloned repository workspace.
          2. git checkout -b <branch>
          3. git add <files>
          4. git commit
          5. git push origin <branch>
          6. Attempt gh pr create (optional — skipped gracefully if gh absent)
        """
        workspace_path = plan["workspace_path"]
        branch_name = plan["branch_name"]
        commit_message = plan["commit_message"]
        file_paths = plan["files"]

        workspace = Path(workspace_path).resolve()

        # Write automation files into the repo workspace
        for auto_file in automation_artifact.files:
            target = (workspace / auto_file.path).resolve()
            try:
                target.relative_to(workspace)
            except ValueError as exc:
                raise ValueError(
                    f"Automation file path escapes workspace: {auto_file.path}"
                ) from exc
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(auto_file.content, encoding="utf-8")

        logger.info(
            "code_push: wrote %d file(s) into repo | workspace=%s",
            len(automation_artifact.files),
            workspace_path,
        )

        # Create new branch
        self._git(workspace_path, ["checkout", "-b", branch_name])

        # Stage the automation files
        for path in file_paths:
            self._git(workspace_path, ["add", path])

        # Commit
        self._git(workspace_path, ["commit", "-m", commit_message])
        logger.info("code_push: committed | branch=%s", branch_name)

        # Push to remote
        self._git(workspace_path, ["push", "origin", branch_name])
        logger.info("code_push: pushed | branch=%s", branch_name)

        # Attempt PR creation
        pr_url = self._try_create_pr(workspace_path, branch_name, commit_message)

        return {
            "branch": branch_name,
            "files_committed": len(file_paths),
            "pr_url": pr_url,
            "workspace_path": workspace_path,
        }

    # ==========================================================
    # Git helpers
    # ==========================================================

    @staticmethod
    def _git(cwd: str, args: list[str]) -> str:
        result = subprocess.run(
            ["git"] + args,
            cwd=cwd,
            capture_output=True,
            text=True,
            timeout=120,
        )
        if result.returncode != 0:
            raise RuntimeError(
                f"git {args[0]} failed (exit {result.returncode}): "
                f"{(result.stderr or result.stdout).strip()}"
            )
        return result.stdout.strip()

    @staticmethod
    def _try_create_pr(cwd: str, branch: str, commit_message: str) -> str | None:
        """
        Attempt to create a PR using the GitHub CLI (gh).
        Returns the PR URL on success; None if gh is absent or the call fails.
        """
        title = commit_message.split("\n")[0]
        body = (
            "Generated by QAgentic automated test suite.\n\n"
            + commit_message
        )
        try:
            result = subprocess.run(
                [
                    "gh", "pr", "create",
                    "--head", branch,
                    "--title", title,
                    "--body", body,
                ],
                cwd=cwd,
                capture_output=True,
                text=True,
                timeout=60,
            )
            if result.returncode == 0:
                pr_url = result.stdout.strip()
                logger.info("code_push: PR created | url=%s", pr_url)
                return pr_url

            logger.info(
                "code_push: gh pr create returned exit %d — "
                "branch pushed without PR | stderr=%s",
                result.returncode,
                result.stderr.strip()[:300],
            )

        except FileNotFoundError:
            logger.info(
                "code_push: gh CLI not found — branch pushed without PR"
            )
        except subprocess.TimeoutExpired:
            logger.info(
                "code_push: gh pr create timed out — branch pushed without PR"
            )
        return None

    @staticmethod
    def _generate_branch_name(requirement: str) -> str:
        slug = re.sub(r"[^a-z0-9]+", "-", requirement.lower())[:40].strip("-")
        timestamp = int(time.time())
        return f"qagentic/{slug}-{timestamp}"

from dataclasses import dataclass, field
from typing import Any


@dataclass(slots=True)
class ExecutionCommand:
    """
    Represents a deterministic command that can execute tests
    discovered from a repository.

    The command is intentionally represented as arguments rather
    than a shell string so that execution providers can decide how
    to safely invoke it.
    """

    executable: str
    arguments: list[str] = field(default_factory=list)
    description: str = ""
    suite: str | None = None

    @property
    def command(self) -> str:
        """
        Returns a human-readable command representation.
        """

        parts = [self.executable, *self.arguments]

        return " ".join(
            self._quote_if_required(part)
            for part in parts
        )

    @staticmethod
    def _quote_if_required(value: str) -> str:
        if not value:
            return '""'

        if any(character.isspace() for character in value):
            return f'"{value}"'

        return value

    def to_dict(self) -> dict[str, Any]:
        return {
            "executable": self.executable,
            "arguments": list(self.arguments),
            "description": self.description,
            "suite": self.suite,
            "command": self.command,
        }


@dataclass(frozen=True, slots=True)
class SuiteCandidate:
    """
    Generic test-suite/filter candidate discovered from a repository.

    This model is framework and build-tool agnostic.

    A candidate may optionally provide a deterministic execution
    command when repository discovery can establish one.
    """

    name: str

    mechanism: str

    selector: str | None = None

    source: str | None = None

    command: ExecutionCommand | None = None

    deterministic: bool = False

    confidence: float = 0.0

    metadata: dict[str, Any] = field(
        default_factory=dict
    )

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "mechanism": self.mechanism,
            "selector": self.selector,
            "source": self.source,
            "command": (
                self.command.to_dict()
                if self.command is not None
                else None
            ),
            "deterministic": self.deterministic,
            "confidence": self.confidence,
            "metadata": dict(self.metadata),
        }


@dataclass(slots=True)
class RepositoryExecutionProfile:
    """
    Describes how a repository can be executed.

    This is a discovery result, not an execution instruction
    generated by the LLM.

    The profile answers:

        - What type of project is this?
        - Which test framework is present?
        - Which runner should be used?
        - Where are the tests?
        - Which suite-selection mechanisms exist?
        - Can the requested suite be selected deterministically?
        - Which execution command should be used?

    It deliberately does not execute anything.
    """

    project_types: list[str] = field(default_factory=list)

    frameworks: list[str] = field(default_factory=list)

    test_locations: list[str] = field(default_factory=list)

    configuration_files: list[str] = field(default_factory=list)

    runner_candidates: list[str] = field(default_factory=list)

    suite_candidates: list[SuiteCandidate] = field(
        default_factory=list
    )

    execution_commands: list[ExecutionCommand] = field(
        default_factory=list
    )

    working_directory: str | None = None

    selected_framework: str | None = None

    selected_runner: str | None = None

    requested_suite: str | None = None

    selected_suite: SuiteCandidate | None = None

    deterministic: bool = False

    confidence: float = 0.0

    metadata: dict[str, Any] = field(default_factory=dict)

    @property
    def can_execute(self) -> bool:
        """
        Returns True when a deterministic execution command
        has been identified.
        """

        return bool(
            self.execution_commands
            and self.deterministic
        )

    @property
    def selected_command(self) -> ExecutionCommand | None:
        """
        Returns the execution command to use.

        When a suite is selected, prefers the command whose suite
        field matches the selected suite name.  Falls back to the
        first command when no suite-specific command exists.
        """

        if not self.execution_commands:
            return None

        if self.selected_suite:
            suite_name = self.selected_suite.name
            for cmd in self.execution_commands:
                if cmd.suite == suite_name:
                    return cmd

        return self.execution_commands[0]

    def add_suite_candidate(
        self,
        candidate: SuiteCandidate,
    ) -> None:
        """
        Add a suite candidate without creating duplicates.
        """

        for existing in self.suite_candidates:
            if (
                existing.name == candidate.name
                and existing.mechanism == candidate.mechanism
                and existing.selector == candidate.selector
            ):
                return

        self.suite_candidates.append(candidate)

    def add_execution_command(
        self,
        command: ExecutionCommand,
    ) -> None:
        """
        Add an execution command without duplicates.
        """

        for existing in self.execution_commands:
            if existing.command == command.command:
                return

        self.execution_commands.append(command)

    def select_suite(
        self,
        suite_name: str,
    ) -> SuiteCandidate | None:
        """
        Select a deterministic suite candidate by name.

        Matching is case-insensitive.
        """

        if not suite_name:
            return None

        requested = suite_name.strip().lower()

        for candidate in self.suite_candidates:
            if candidate.name.strip().lower() == requested:
                self.requested_suite = suite_name
                self.selected_suite = candidate

                if candidate.command:
                    # Suite has its own command — use it and inherit
                    # the suite's determinism flag.
                    self.execution_commands = [
                        candidate.command
                    ]
                    self.deterministic = candidate.deterministic
                # When the suite has no command the general execution
                # command (already on the profile) remains in effect
                # and the profile-level deterministic flag is preserved.

                self.confidence = candidate.confidence

                return candidate

        return None

    def to_dict(self) -> dict[str, Any]:
        """
        Convert the profile into a serializable representation.
        """

        return {
            "project_types": list(self.project_types),
            "frameworks": list(self.frameworks),
            "test_locations": list(self.test_locations),
            "configuration_files": list(
                self.configuration_files
            ),
            "runner_candidates": list(
                self.runner_candidates
            ),
            "suite_candidates": [
                candidate.to_dict()
                for candidate in self.suite_candidates
            ],
            "execution_commands": [
                command.to_dict()
                for command in self.execution_commands
            ],
            "working_directory": self.working_directory,
            "selected_framework": self.selected_framework,
            "selected_runner": self.selected_runner,
            "requested_suite": self.requested_suite,
            "selected_suite": (
                self.selected_suite.to_dict()
                if self.selected_suite
                else None
            ),
            "deterministic": self.deterministic,
            "confidence": self.confidence,
            "metadata": dict(self.metadata),
        }

    def set_selected_suite(
        self,
        suite_name: str,
    ) -> SuiteCandidate | None:
        """
        Select a suite candidate without changing the general
        execution strategy.

        Matching order:
          1. Exact name match (case-insensitive)
          2. Name starts with the requested value
          3. Name contains the requested value
          4. selector or source contains the requested value
        """

        if not suite_name:
            return None

        requested = suite_name.strip().lower()

        def _rank(candidate: SuiteCandidate) -> int:
            name = candidate.name.strip().lower()
            selector = (candidate.selector or "").lower()
            source = (candidate.source or "").lower()
            if name == requested:
                return 0
            if name.startswith(requested):
                return 1
            if requested in name:
                return 2
            if requested in selector or requested in source:
                return 3
            return 99

        matches = [
            c for c in self.suite_candidates
            if _rank(c) < 99
        ]

        if not matches:
            return None

        best = min(matches, key=_rank)
        self.requested_suite = suite_name
        self.selected_suite = best
        return best